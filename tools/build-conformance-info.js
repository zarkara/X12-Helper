/*
 * Writes an .info sidecar next to every file in the conformance corpus, and
 * checks that each file still hashes to what the manifest says it should.
 *
 *   node tools/build-conformance-info.js            write the sidecars
 *   node tools/build-conformance-info.js --check    verify without writing
 *
 * The manifest is the record; the sidecars are a rendering of it, so that
 * anyone who opens a single message file can see where it came from and what
 * licence it arrived under without going looking. Both are checked by
 * tests/conformance.test.js.
 *
 * Everything here is derived from the manifest, which was built by matching
 * each captured file against the blob at a named commit in the upstream
 * repository. "Verified" in a sidecar means that comparison was byte-exact.
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const STANDARD = 'x12-835';
const CORPUS = path.join(__dirname, '..', 'conformance', STANDARD);
const MANIFEST = path.join(CORPUS, 'manifest.json');
const NOTICE = path.join(__dirname, '..', 'conformance', 'NOTICE');
const WIDTH = 15;
const RULE = '-'.repeat(78);

function render(entry, source) {
  const licenceCopy = path.posix.relative(path.posix.dirname(entry.file), path.posix.join(entry.source, 'LICENSE')) || 'LICENSE';
  const line = (label, value) => (value ? `${(label + ':').padEnd(WIDTH)}${value}\n` : '');
  const wrap = (label, value) => {
    if (!value) return '';
    const words = String(value).split(' ');
    const lines = [];
    let current = '';
    for (const word of words) {
      if (current && (current + ' ' + word).length > 78 - WIDTH) { lines.push(current); current = word; }
      else current = current ? `${current} ${word}` : word;
    }
    if (current) lines.push(current);
    return `${(label + ':').padEnd(WIDTH)}${lines.join(`\n${' '.repeat(WIDTH)}`)}\n`;
  };

  return [
    `${path.posix.basename(entry.file)}\n`,
    `${'='.repeat(path.posix.basename(entry.file).length)}\n`,
    '\n',
    line('File', path.posix.basename(entry.file)),
    line('SHA-256', entry.sha256),
    line('Bytes', String(entry.bytes)),
    '\n',
    line('Source', source.name),
    line('Repository', source.repository),
    line('Commit', entry.commit),
    line('Upstream path', entry.upstreamPath),
    line('Permalink', entry.permalink),
    line('Retrieved', entry.retrieved),
    entry.verified ? wrap('Verified', `This file is ${entry.verified}.`) : '',
    entry.excerptOf ? wrap('Excerpt of', `${entry.excerptOf} (SHA-256 ${entry.originalSha256}, ${entry.originalBytes} bytes). ${entry.excerptNote}`) : '',
    '\n',
    line('Licence', source.licence),
    wrap('Licence text', `${source.licenceUrl} (copy: ${licenceCopy})`),
    wrap('Copyright', source.copyright),
    wrap('Attribution', source.attribution),
    '\n',
    wrap('Content', source.origin),
    wrap('Covers', source.covers),
    '\n',
    wrap('Note', 'This file was written by the source above, not by this project. It is redistributed unchanged under the licence named here. See conformance/README.md and conformance/NOTICE.'),
  ].join('');
}

/* NOTICE is generated too, so a source can never be added to the corpus and
 * left out of the attribution. */
function renderNotice(manifest) {
  const counts = {};
  manifest.files.forEach((entry) => { counts[entry.source] = (counts[entry.source] || 0) + 1; });
  const blocks = Object.entries(manifest.sources).map(([slug, source]) => [
    `conformance/${STANDARD}/${slug}/  (${counts[slug] || 0} file${counts[slug] === 1 ? '' : 's'})`,
    `Source:      ${source.name} — ${source.repository}`,
    `Licence:     ${source.licence} — ${source.licenceUrl}`,
    `             Full text: conformance/${STANDARD}/${slug}/LICENSE`,
    `Copyright:   ${source.copyright}`,
    `Attribution: ${source.attribution}`,
  ].join('\n')).join(`\n\n${RULE}\n\n`);

  return [
    `Third-party test files redistributed in this Apache-2.0 project.`,
    '',
    'Every file here was written by the source named below, not by this project,',
    'and is redistributed unchanged under that source\'s licence. Each file has an',
    '.info sidecar recording the upstream repository, commit, path and content',
    'hash it was taken from; conformance/' + STANDARD + '/manifest.json holds the same',
    'record in full, and npm test verifies it.',
    '',
    'All of it is synthetic or scrubbed. None of it contains real patient data.',
    '',
    'This file is generated by tools/build-conformance-info.js. Do not edit it by',
    'hand — edit the manifest and regenerate.',
    '',
    RULE,
    '',
    blocks,
    '',
    RULE,
    '',
  ].join('\n');
}

function main() {
  const checkOnly = process.argv.includes('--check');
  const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
  const problems = [];
  let written = 0;

  for (const entry of manifest.files) {
    const source = manifest.sources[entry.source];
    if (!source) { problems.push(`${entry.file}: manifest has no source record for "${entry.source}"`); continue; }

    const dataPath = path.join(CORPUS, entry.file);
    if (!fs.existsSync(dataPath)) { problems.push(`${entry.file}: listed in the manifest but not on disk`); continue; }

    const actual = crypto.createHash('sha256').update(fs.readFileSync(dataPath)).digest('hex');
    if (actual !== entry.sha256) {
      problems.push(`${entry.file}: content has changed since it was captured (manifest ${entry.sha256.slice(0, 12)}…, on disk ${actual.slice(0, 12)}…)`);
      continue;
    }

    const infoPath = `${dataPath}.info`;
    const contents = render(entry, source);
    const current = fs.existsSync(infoPath) ? fs.readFileSync(infoPath, 'utf8') : null;
    if (current === contents) continue;
    if (checkOnly) { problems.push(`${entry.file}.info is out of date`); continue; }
    fs.writeFileSync(infoPath, contents);
    written += 1;
  }

  const notice = renderNotice(manifest);
  if (fs.readFileSync(NOTICE, 'utf8') !== notice) {
    if (checkOnly) problems.push('conformance/NOTICE is out of date');
    else { fs.writeFileSync(NOTICE, notice); written += 1; }
  }

  // A data file with no manifest entry has no provenance, which is the one
  // thing this corpus must never contain.
  const known = new Set(manifest.files.map((entry) => entry.file));
  (function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) { walk(full); continue; }
      if (entry.name === 'LICENSE' || entry.name === 'manifest.json' || entry.name.endsWith('.info')) continue;
      const relative = path.relative(CORPUS, full).split(path.sep).join('/');
      if (!known.has(relative)) problems.push(`${relative}: on disk with no manifest entry, so no recorded source or licence`);
    }
  })(CORPUS);

  if (problems.length) {
    problems.forEach((problem) => console.error(problem));
    console.error(`\n${problems.length} problem(s).`);
    process.exit(1);
  }
  console.log(checkOnly
    ? `${manifest.files.length} files verified against the manifest; every .info is current.`
    : `${manifest.files.length} files verified, ${written} .info file(s) written.`);
}

main();
