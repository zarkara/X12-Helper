/*
 * Rewrites conformance/baseline.json from the current dictionary.
 *
 * Run it after changing the dictionary or adding a corpus file, then read the
 * diff. Counts going down is the point. Counts going up means something is no
 * longer explained, which belongs in the commit message.
 */
const fs = require('node:fs');
const { loadCore } = require('../tests/load');
const { report, totals, BASELINE } = require('./conformance-report');

const result = report(loadCore());
const baseline = {
  note: 'Generated by tools/update-conformance-baseline.js. Do not edit by hand.',
  totals: totals(result),
  parseFailures: result.parseFailures,
  unknownSegments: result.unknownSegments,
  elementsPastDictionary: result.elementsPastDictionary,
  undefinedTables: result.undefinedTables,
  codesNotInTable: result.codesNotInTable,
  envelopeWarnings: result.envelopeWarnings,
  unbalanced: result.unbalanced,
};

fs.writeFileSync(BASELINE, `${JSON.stringify(baseline, null, 2)}\n`);
console.log(JSON.stringify(baseline.totals, null, 2));
